def esc(s):
	return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
	missing = [s for s in strings() if s not in ES and s not in CTX]
	lines = ['msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"', '"Language: es\\n"', ""]
	for k, v in ES.items():
		lines += [f'msgid "{esc(k)}"', f'msgstr "{esc(v)}"', ""]
	for k, by_ctx in CTX.items():
		for ctx, v in by_ctx.items():
			lines += [f'msgctxt "{esc(ctx)}"', f'msgid "{esc(k)}"', f'msgstr "{esc(v)}"', ""]
	os.makedirs(os.path.join(ROOT, "quest_automations/locale"), exist_ok=True)
	with open(os.path.join(ROOT, "quest_automations/locale/es.po"), "w", encoding="utf-8") as f:
		f.write("\n".join(lines))
	print(f"{len(ES)} strings written; {len(missing)} missing")
	for m in missing:
		print("  missing:", m)


if __name__ == "__main__":
	main()
